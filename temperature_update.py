"""
Temperature update for the Nelson & Langer (1999) thermal model, using the code generated by jaco.

The generated function (c/microphysics_func_jac.c compiled with its batch wrapper) returns
the residual of the implicit (backward Euler) energy equation for u and T, and its Jacobian. The functions here run a
Newton-Raphson iteration around it to find the temperature after a time step dt with the abundances, the density and
the radiation field held fixed.

Units are CGS: T in K, dt in s, n_H in cm^-3, abundances per H nucleus, pdv_work in erg cm^-3 s^-1, G_0 in Habing units
and dv_dr in s^-1.
"""

import ctypes
import subprocess
from pathlib import Path

import numpy as np
from numpy.ctypeslib import ndpointer
from scipy.optimize import brentq


DIRECTORY = Path(__file__).resolve().parent
C_DIRECTORY = DIRECTORY / "c"
LIBRARY = C_DIRECTORY / "libnelson_batch.so"

# The abundances, per H nucleus, that are inputs.
SPECIES = ("H_2", "H3+", "He+", "CH", "OH", "CO", "C+", "HCO+", "Mg+")

# The inputs that can be left out. The elemental totals are those of Nelson & Langer (1999), per H nucleus.
DEFAULTS = {
    "y":        0.14,
    "x_C,tot":  5e-5,
    "x_O,tot":  1e-4,
    "x_Mg,tot": 5e-8,
    "G_0":      1.0,
    "A_V":      0.0,
    "tau_uv":   0.0,
    "dv_dr":    3.2408e-14,
    "pdv_work": 0.0
}


def compile_library():
    """
    Compiles the generated C function and its batch wrapper into a shared library. Needs gcc.
    """
    subprocess.run([
        "gcc", "-O2", "-shared", "-fPIC", "-o", str(LIBRARY),
        str(C_DIRECTORY / "batch_func_jac.c"), str(C_DIRECTORY / "microphysics_func_jac.c"), "-lm"
    ], check=True)


def load_library():
    """
    Loads the shared library, compiling it first if it does not exist, and declares its batch function.
    """
    if not LIBRARY.exists():
        compile_library()

    library = ctypes.CDLL(str(LIBRARY))
    pointer = ndpointer(np.float64, flags="C_CONTIGUOUS")
    library.batch_func_jac.argtypes = [ctypes.c_int, pointer, pointer, pointer, pointer]
    library.batch_func_jac.restype = None
    return library


lib = load_library()
param_names = [
    'A_V',
    'Delta_t',
    'G_0',
    'dv_dr',
    'n_Htot',
    'pdv_work',
    'tau_uv',
    'u_initial',
    'x_CH',
    'x_CO',
    'x_C_tot',
    'x_Cplus',
    'x_H3plus',
    'x_HCOplus',
    'x_H_2',
    'x_Heplus',
    'x_Mg_tot',
    'x_Mgplus',
    'x_OH',
    'x_O_tot',
    'y'
]


def sanitize(name):
    """
    Returns the way the generated code spells a name, e.g. "x_C,tot" -> "x_C_tot" and "x_C+" -> "x_Cplus".
    """
    return name.replace("+", "plus").replace(",", "_")


def batch_residual(X, P):
    """
    X: (n, 2) = (u, T), P: (n, number of parameters) in the order of `param_names`; returns rhs (n, 2) and jac (n, 2, 2)
    """
    X, P = np.ascontiguousarray(X, dtype=float), np.ascontiguousarray(P, dtype=float)
    rhs, jac = np.empty((len(X), 2)), np.empty((len(X), 2, 2))
    lib.batch_func_jac(len(X), X, P, rhs, jac)
    return rhs, jac


def update_temperatures_batch(T, dt, n_H, species, rtol=1e-10, max_iter=60, **physical):
    """
    Computes the temperature after a step dt in every cell. Returns (T_new, iterations), arrays of the broadcast shape.

    The returned iterations is -1 when the batched Newton iteration fails and a bracketing solver was used instead.
    """
    values = {
        "Delta_t": dt,
        "n_Htot": n_H,
        **{sanitize(k): v for k, v in {**DEFAULTS, **physical}.items()},
        **{sanitize(f"x_{s}"): species[s] for s in SPECIES}
    }
    names = [name for name in param_names if name != "u_initial"]

    T, *columns = np.broadcast_arrays(np.asarray(T, float), *(np.asarray(values[name], float) for name in names))
    T0 = T.ravel()

    P = np.zeros((T0.size, len(param_names)))
    for name, column in zip(names, columns):
        P[:, param_names.index(name)] = column.ravel()

    i_dt = param_names.index("Delta_t")
    i_u0 = param_names.index("u_initial")

    # Set initial state X using the residual at u = 0.
    dt_cells   = P[:, i_dt].copy()
    P[:, i_dt] = 1.0
    P[:, i_u0] = batch_residual(np.column_stack([np.zeros_like(T0), T0]), P)[0][:, 0]
    P[:, i_dt] = dt_cells
    X = np.column_stack([P[:, i_u0], T0])

    T_new      = np.full(T0.size, np.nan)      # To hold the new temperatures.
    iterations = np.zeros(T0.size, dtype=int)  # Tracks the number of Newton Raphson iterations.
    active     = np.arange(T0.size)            # Tracks the cells that are still being updated.
    failed     = []                            # Tracks the cells that failed to converge.

    # Newton-Raphson loop.
    with np.errstate(all="ignore"):
        for iteration in range(1, max_iter + 1):
            if active.size == 0:
                break

            # Compute the Newton update step.
            rhs, jac = batch_residual(X[active], P[active])
            a, b = jac[:, 0, 0], jac[:, 0, 1]
            c, d = jac[:, 1, 0], jac[:, 1, 1]
            step = -np.column_stack([
                d * rhs[:, 0] - b * rhs[:, 1],
                a * rhs[:, 1] - c * rhs[:, 0]
            ]) / (a * d - b * c)[:, None]

            # Scale the step so that the absolute change in T is at most 50%.
            dT = step[:, 1]
            scale = np.where(dT != 0, np.minimum(1.0, 0.5 * X[active, 1] / np.abs(dT)), 1.0)
            X[active] += scale[:, None] * step

            # Update which cells are active and record converged temperatures.
            broken = ~np.isfinite(X[active]).all(axis=1)
            converged = ~broken & (scale == 1.0) & (np.abs(dT) < rtol * X[active, 1])
            T_new[active[converged]] = X[active[converged], 1]
            iterations[active[converged]] = iteration
            failed.extend(active[broken])
            active = active[~broken & ~converged]

    # Use the scalar version, with its bracketing root find, to update the failed cells.
    failed.extend(active)
    for j in failed:
        T_new[j], iterations[j] = update_temperature_scalar(
            T0[j], P[j, i_dt], P[j, param_names.index("n_Htot")],
            {s: P[j, param_names.index(sanitize(f"x_{s}"))] for s in SPECIES},
            rtol=rtol, max_iter=max_iter, **{k: P[j, param_names.index(sanitize(k))] for k in DEFAULTS}
        )

    shape = T.shape
    return T_new.reshape(shape), iterations.reshape(shape)


def initial_energy(P, T0):
    """
    Returns u_eos(T0) in every cell, the first residual at u = 0, for the parameters in the rows of P.
    """
    P = P.copy()
    P[:, param_names.index("Delta_t")] = 1.0
    return batch_residual(np.column_stack([np.zeros_like(T0), T0]), P)[0][:, 0]


def batch_parameters(T, dt, n_H, species, **physical):
    """
    Returns the broadcast shape, the initial temperatures and the parameters of every cell.

    The initial temperatures are raveled and the parameters are a matrix with a row per cell, in the order of
    `param_names` and including u_initial from the equation of state.
    """
    values = {
        "Delta_t": dt,
        "n_Htot": n_H,
        **{sanitize(k): v for k, v in {**DEFAULTS, **physical}.items()},
        **{sanitize(f"x_{s}"): species[s] for s in SPECIES}
    }
    names = [name for name in param_names if name != "u_initial"]

    T, *columns = np.broadcast_arrays(np.asarray(T, float), *(np.asarray(values[name], float) for name in names))
    T0 = T.ravel()

    P = np.zeros((T0.size, len(param_names)))
    for name, column in zip(names, columns):
        P[:, param_names.index(name)] = column.ravel()
    P[:, param_names.index("u_initial")] = initial_energy(P, T0)

    return T.shape, T0, P


def parameter_vector(n_H, species, dt, u_initial=0.0, **physical):
    """
    Returns the parameter vector of the generated code, in its own order, from named inputs.
    """
    values = {
        "n_Htot": n_H,
        "Delta_t": dt,
        "u_initial": u_initial,
        **{sanitize(k): v for k, v in {**DEFAULTS, **physical}.items()},
        **{sanitize(f"x_{s}"): species[s] for s in SPECIES}
    }
    return np.array([values[name] for name in param_names], dtype=float)


def residual(X, params):
    """Return the residual and Jacobian for one state using the C batch evaluator."""
    rhs, jac = batch_residual(np.asarray(X)[None, :], np.asarray(params)[None, :])
    return rhs[0], jac[0]


def internal_energy(T, n_H, species, **physical):
    """
    Returns u_eos(T), the internal energy given by the equation of state. It is the first residual at u = 0.
    """
    return residual(np.array([0.0, T]), parameter_vector(n_H, species, 1.0, **physical))[0][0]


def update_temperature_scalar(T, dt, n_H, species, rtol=1e-10, max_iter=60, **physical):
    """
    Computes the temperature after a step dt in one cell. Returns (T_new, iterations).

    species is {name: abundance per H nucleus} and physical holds G_0, A_V, tau_uv, dv_dr, pdv_work and the elemental
    totals. Newton-Raphson is run on (u, T) with the generated Jacobian. If it fails, which it can from a very low T
    with a very long step at high density, a bracketing root find on the energy equation is used and iterations is -1.
    """
    p = parameter_vector(n_H, species, dt, **physical)
    u_initial = internal_energy(T, n_H, species, **physical)
    p[param_names.index("u_initial")] = u_initial

    # Newton-Raphson loop.
    try:
        X = np.array([u_initial, T])
        rhs, jac = residual(X, p)
        for iteration in range(1, max_iter + 1):
            step = np.linalg.solve(jac, -rhs)

            # Scale the step so that the absolute change in T is at most 50%, which also keeps T positive.
            scale = min(1.0, 0.5 * X[1] / abs(step[1])) if step[1] != 0 else 1.0
            X = X + scale * step
            rhs, jac = residual(X, p)
            if scale == 1.0 and abs(step[1]) < rtol * X[1]:
                return X[1], iteration

    except (OverflowError, FloatingPointError, np.linalg.LinAlgError):
        pass

    # Bracketing root find on the energy equation, with u = u_eos(T_new).
    def energy_residual(T_new):
        return residual(np.array([internal_energy(T_new, n_H, species, **physical), T_new]), p)[0][1]

    T_lo, T_hi = 1.0, 1e5
    if not energy_residual(T_lo) > 0 > energy_residual(T_hi):
        raise RuntimeError(f"no solution between {T_lo} and {T_hi} K for T = {T}, dt = {dt:g}, n_H = {n_H:g}")
    return brentq(energy_residual, T_lo, T_hi, xtol=1e-12, rtol=1e-12), -1


def update_temperatures_scalar(T, dt, n_H, species, **physical):
    """
    Computes the temperature after a step dt in every cell, with a loop over update_temperature_scalar.

    T, n_H and the abundances broadcast. Returns T_new, an array of the broadcast shape.
    """
    T, n_H = np.broadcast_arrays(np.asarray(T, float), np.asarray(n_H, float))
    shape = T.shape
    spec_arrays = {k: np.broadcast_to(np.asarray(v, float), shape).ravel() for k, v in species.items()}
    return np.array([
        update_temperature_scalar(Ti, dt, ni, {k: v[j] for k, v in spec_arrays.items()}, **physical)[0]
        for j, (Ti, ni) in enumerate(zip(T.ravel(), n_H.ravel()))
    ]).reshape(shape)
