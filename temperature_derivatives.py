"""
Exact derivatives of the new temperature with respect to the abundances, using generated code.

c/microphysics_dabundances.c, generated by jaco's model and sympy, returns the derivatives of the residual of the implicit
energy equation, the function in temperature_update.py, with respect to the abundance of each species and to u_initial.
The derivatives of the new temperature then follow from the implicit function theorem.
"""

import ctypes
import subprocess

import numpy as np
from numpy.ctypeslib import ndpointer

from temperature_update import C_DIRECTORY, SPECIES, batch_parameters, batch_residual, initial_energy, param_names, sanitize


LIBRARY = C_DIRECTORY / "libnelson_dabundances.so"

# The columns of the derivatives, as in the generated enum DerivativeIndex: the species and then u_initial.
COLUMNS = [f"x_{sanitize(s)}" for s in SPECIES] + ["u_initial"]


def compile_library():
    """
    Compiles the generated derivatives and their batch wrapper into a shared library. Needs gcc.
    """
    subprocess.run([
        "gcc", "-O2", "-shared", "-fPIC", "-I", str(C_DIRECTORY), "-o", str(LIBRARY),
        str(C_DIRECTORY / "batch_dabundances.c"), str(C_DIRECTORY / "microphysics_dabundances.c"), "-lm"
    ], check=True)


def load_library():
    """
    Loads the shared library, compiling it first if it does not exist, and declares its batch function.
    """
    header = (C_DIRECTORY / "microphysics_dabundances.h").read_text()
    for k, name in enumerate(COLUMNS):
        assert f"D_{name} = {k}" in header, f"the generated derivatives do not have {name} in column {k}"

    if not LIBRARY.exists():
        compile_library()

    library = ctypes.CDLL(str(LIBRARY))
    pointer = ndpointer(np.float64, flags="C_CONTIGUOUS")
    library.batch_dabundances.argtypes = [ctypes.c_int, pointer, pointer, pointer]
    library.batch_dabundances.restype = None
    return library


lib = load_library()


def batch_dabundances(X, P):
    """
    X: (n, 2) = (u, T), P: (n, number of parameters) in the order of `param_names`; returns dF (n, 2, len(COLUMNS)), the
    derivatives of the two residuals with respect to the columns
    """
    X, P = np.ascontiguousarray(X, dtype=float), np.ascontiguousarray(P, dtype=float)
    dF = np.empty((len(X), 2, len(COLUMNS)))
    lib.batch_dabundances(len(X), X, P, dF)
    return dF


def temperature_derivatives_batch(T, dt, n_H, species, T_new, **physical):
    """
    Computes the derivative of the new temperature with respect to the abundance of each species, in every cell.

    Returns a dictionary {species: derivative}, with arrays of the broadcast shape in K per unit abundance (per H
    nucleus). T is the initial temperature and T_new the result of update_temperatures_batch for the same inputs.

    The derivatives hold the initial temperature, the time step, the elemental totals and all the other inputs fixed, so
    the neutral C, O, He and Mg and the electrons change with the abundance through the conservation laws.

    At the solution X = (u, T_new) the residual F(X, x) of the generated function is zero for the abundances x, so by the
    implicit function theorem dX/dx = -J^-1 dF/dx, where J is the Jacobian the generated function returns. This needs
    no derivative of the Newton iterations. u_initial is the equation of state at the initial temperature, so it also
    depends on the abundances, and dF/dx is the total derivative dF/dx + dF/du_initial * du_initial/dx. The last factor
    is the derivative of the first residual, u_eos(T) - u, at the initial state.
    """
    n_species = len(SPECIES)
    shape, T0, P = batch_parameters(T, dt, n_H, species, **physical)
    T_new = np.broadcast_to(np.asarray(T_new, float), shape).ravel()

    # The solution X, with u from the equation of state, and the Jacobian there.
    X = np.column_stack([initial_energy(P, T_new), T_new])
    a, b, c, d = batch_residual(X, P)[1].reshape(-1, 4).T
    det = a * d - b * c

    # The derivatives of the residuals at the solution and, for u_initial, of the first residual at the initial state.
    dF = batch_dabundances(X, P)
    X_initial = np.column_stack([P[:, param_names.index("u_initial")], T0])
    du_initial = batch_dabundances(X_initial, P)[:, 0, :n_species]

    # The total derivative of the residuals with respect to each abundance, and the T component of -J^-1 dF/dx.
    total = dF[:, :, :n_species] + dF[:, :, [-1]] * du_initial[:, None, :]
    dT = (c[:, None] * total[:, 0, :] - a[:, None] * total[:, 1, :]) / det[:, None]

    return {s: dT[:, k].reshape(shape) for k, s in enumerate(SPECIES)}
